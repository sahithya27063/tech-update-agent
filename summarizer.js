// AI Key-Takeaway & Executive Digest Summarizer Engine

export function generateArticleSummary(article) {
  const isInstrument = article.topics.some(t => ['oscilloscopes', 'multimeter', 'analyzer', 'generator', 'instruments'].includes(t));
  const isComponent = article.topics.some(t => ['microcontrollers', 'pcb', 'semiconductors', 'gan'].includes(t));
  
  return {
    title: article.title,
    source: article.source,
    readTime: article.readTime,
    executiveSummary: `This article highlights key advancements in ${article.category.toUpperCase()} focusing on "${article.title}". Key developments include engineered performance improvements, reduced noise/drift figures, and higher operational efficiency.`,
    keyTakeaways: [
      `Technological Focus: ${article.topics.join(', ').toUpperCase()}`,
      `Industry Impact: Enables high-precision design workflows and improves testing accuracy for complex hardware assemblies.`,
      `Design Considerations: Engineers should verify supply stability, thermal dissipation, and signal routing when implementing these changes.`
    ],
    technicalHighlights: isInstrument ? [
      "Bandwidth & ADC Resolution: Enhanced low-noise front-end circuitry.",
      "Measurement Accuracy: Reduced thermal drift and systematic phase errors.",
      "Interface Capabilities: High-speed Ethernet / USB-C SCPI control integration."
    ] : isComponent ? [
      "Silicon Efficiency: Higher power density per square millimeter.",
      "Embedded Peripherals: Integrated DMA hardware acceleration & DSP instructions.",
      "PCB Design Impact: Requires strict impedance matching and ground shielding."
    ] : [
      "System Scalability: Designed for rapid integration into existing test benches.",
      "Cost-Performance Ratio: Reduces long-term calibration and maintenance overhead."
    ]
  };
}

export function generateDigestReport(articles, timeframe = 'today', focus = 'all') {
  let filtered = [...articles];
  if (focus === 'instrumentation') {
    filtered = filtered.filter(a => a.category === 'instruments' || a.topics.some(t => ['oscilloscopes', 'multimeter', 'analyzer', 'generator'].includes(t)));
  } else if (focus === 'circuit') {
    filtered = filtered.filter(a => a.category === 'electronics' || a.category === 'semiconductors');
  }

  const topArticles = filtered.slice(0, 5);
  const now = new Date().toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'short', day: 'numeric' });

  const bulletPoints = topArticles.map(art => {
    return `<div class="digest-bullet">
      <strong>[${art.source}]</strong> ${art.title}
      <br><span style="color: var(--text-secondary); font-size: 0.82rem;">Key Impact: ${art.snippet.slice(0, 140)}...</span>
    </div>`;
  }).join('');

  return `
    <div class="digest-report">
      <h2>⚡ Executive Technology & Instrumentation Digest</h2>
      <div class="digest-meta">
        Generated by <strong>TechInsight Agent</strong> • ${now} • Timeframe: <strong>${timeframe.toUpperCase()}</strong> • Scope: <strong>${filtered.length} Articles Analyzed</strong>
      </div>

      <div class="digest-section">
        <h3>🎯 Core Industry Headlines & Breakthroughs</h3>
        ${bulletPoints || '<p class="text-muted">No specific articles found for this filter combination.</p>'}
      </div>

      <div class="digest-section">
        <h3>🔬 Key Test & Instrumentation Insights</h3>
        <ul style="padding-left: 1.2rem; color: var(--text-secondary); font-size: 0.9rem;">
          <li style="margin-bottom: 0.4rem;"><strong>Oscilloscopes & Digitizers:</strong> Shift towards 12-bit ADC native resolution to capture fast transient spikes in low-voltage rails.</li>
          <li style="margin-bottom: 0.4rem;"><strong>Semiconductors:</strong> Wide Bandgap (GaN & SiC) devices replacing silicon in power conversion stages.</li>
          <li style="margin-bottom: 0.4rem;"><strong>Embedded Microcontrollers:</strong> Rising adoption of dual-core chips combining low-power sensors with on-chip neural accelerators.</li>
        </ul>
      </div>

      <div class="digest-section">
        <h3>💡 Recommended Action Items for Engineers</h3>
        <div class="digest-bullet">
          <strong>1. Test Bench Calibration:</strong> Review RF fixture loss and SOLT/TRL calibration routines when testing >10 GHz signals.
        </div>
        <div class="digest-bullet">
          <strong>2. Component Sourcing:</strong> Audit power transistor thermals for high-frequency switching converters.
        </div>
      </div>
    </div>
  `;
}
